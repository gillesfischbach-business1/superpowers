import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { readReport, writeReport, Gate } from './_lib.mjs';

console.log('Release manager — collecting reports and stamping the build');
const gate = new Gate('release');

const files = ['cartographer', 'geologist', 'urbanist', 'architect', 'rail', 'retail', 'systems', 'qa'];
const reports = files.map((f) => ({ id: f, data: readReport(`${f}.json`) }));
const missing = reports.filter((r) => !r.data);
const failedStages = reports.filter((r) => r.data && r.data.passed === false);

let commit = 'uncommitted';
try { commit = execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch (e) { /* not a git checkout */ }

const table = reports.map((r) => `| ${r.id} | ${r.data ? (r.data.passed ? '✅ pass' : '❌ fail') : '—'} | ${r.data?.results ? `${r.data.results.filter((x) => x.ok).length}/${r.data.results.length} gates` : ''} |`).join('\n');
const data = reports.find((r) => r.id === 'systems')?.data || {};
const qa = reports.find((r) => r.id === 'qa')?.data;

const md = `# Diddeleng — build report

Generated by the release agent on ${new Date().toISOString()} at commit \`${commit}\`.

## Stages

| Agent | Result | Detail |
|---|---|---|
${table}

## World

- Seed: **${data.worldHash || 'unknown'}**
- Buildings: **${qa ? '' : ''}${reports.find((r) => r.id === 'urbanist')?.data?.buildings ?? '—'}**
- Windows (instanced): **${data.instances?.windows ?? '—'}**
- Trees: **${data.instances?.trees ?? '—'}**
- Stations: **4** (Burange, Ville, Centre, Usines)
- Interiors: **${qa?.interiors ?? '—'}**
- Quests: **${qa?.quests ?? '—'}**

## Gates

${reports.filter((r) => r.data?.results).map((r) => `### ${r.id}\n\n${r.data.results.map((x) => `- ${x.ok ? '✅' : '❌'} ${x.label}${x.detail ? ` — ${x.detail}` : ''}`).join('\n')}`).join('\n\n')}

## Data accuracy

- Streets, stations, town hall, church, CNA, Parc Le’h and the river anchors: OpenStreetMap (ODbL).
- Elevations: EU-DEM 25 m sampled at 10 × 10 points across the playable area.
- Positions labelled \`approx\` follow addresses / walking distances from the town centre.
- Labels labelled \`model\` are gameplay additions (some side streets, the Budersberg tunnel, the Nei Schmelz block layout).

## Ship

${failedStages.length === 0 && qa?.passed ? 'Green light — the build is shippable.' : 'Blocked — a stage failed; see the table above.'}
`;

fs.writeFileSync(path.join(process.cwd(), 'data', 'reports', 'build-report.md'), md);
fs.mkdirSync(path.join(process.cwd(), 'docs'), { recursive: true });
fs.writeFileSync(path.join(process.cwd(), 'docs', 'build-report.md'), md);

gate.check('all eight upstream reports exist', missing.length === 0, missing.map((m) => m.id).join(', '));
gate.check('no upstream stage failed', failedStages.length === 0, failedStages.map((f) => f.id).join(', '));
gate.check('QA gate is green', qa?.passed === true);
gate.check('build report written', fs.existsSync(path.join(process.cwd(), 'data', 'reports', 'build-report.md')));

writeReport('release.json', {
  agent: 'release', commit, stages: reports.map((r) => ({ id: r.id, passed: r.data?.passed ?? null })), ...gate.finish()
});
console.log('  → docs/build-report.md');
